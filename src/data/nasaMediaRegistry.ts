export function getAssetById(assetId: string): VerifiedNasaAsset | undefined {
  return NASA_MEDIA_REGISTRY.find((a) => a.assetId === assetId);
}

export function getPrimaryDeviceAsset(missionId: MissionId): VerifiedNasaAsset | undefined {
  return NASA_MEDIA_REGISTRY.find(
    (a) => a.deviceId === missionId && a.usageContext === 'device_overview'
  );
}

export function getDeviceComponentAssets(missionId: MissionId): VerifiedNasaAsset[] {
  return NASA_MEDIA_REGISTRY.filter(
    (a) => a.deviceId === missionId && a.usageContext !== 'device_overview'
  );
}

export function getAssetByComponentId(componentId: string): VerifiedNasaAsset | undefined {
  return NASA_MEDIA_REGISTRY.find((a) => a.componentId === componentId);
}
